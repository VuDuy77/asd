// tile type: 0=floor, 1=wall, 2=stair1to2, 3=stair2to3
function wallBetween(x1,y1,x2,y2){
  const dx=x2-x1,dy=y2-y1,len=Math.sqrt(dx*dx+dy*dy),steps=Math.ceil(len/0.12)+1;
  for(let i=1;i<steps;i++){const t=i/steps;if(wall(x1+dx*t,y1+dy*t))return true;}
  return false;
}
